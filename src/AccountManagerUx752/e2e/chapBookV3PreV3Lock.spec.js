/**
 * PictureBook V3 verify check 3 (design §"verify stage exit checks"; ledger P7-5):
 *   "A ChapBook created before V3 renders a page in V3 with its locked prompt intact."
 *
 * LIVE SD over REST against the Docker test stack (chapbook.renderPath=v3, SD at .39). REST only — no browser.
 *
 * The pre-V3 data shape. Before P4-10 a locked ChapBook page prompt lived ONLY on the scene row
 * (olio.pb.scene.sdPrompt + promptLocked=true, written by setSceneLandscapePrompt): no olio.pb.composition
 * row, no scene.sceneNode, no page node. The Docker DB holds 205 CHAPBOOK books and NONE with a locked
 * scene (measured for P7-5), so the shape is BUILT here rather than found: a fresh POST /olio/chap-book/create
 * book (which still creates no composition and links no sceneNode) plus a generic PATCH /rest/model on the
 * scene setting sdPrompt + promptLocked=true — byte-for-byte what the pre-V3 writer persisted. The spec
 * asserts that shape (no page.<sceneOid> composition exists) before it renders.
 *
 * What is proven, in order:
 *   1. POST /olio/chap-book/scene/{id}/generate with no prompt override on that shape goes down v3
 *      (renderPath=v3, rendered=true, llmUnavailable=false, llmDegraded=false) — the lock is honoured by the
 *      find-only composition overlay + resolveScenePrompt, not regenerated by the LLM. The locked text
 *      deliberately begins with "landscape, " so a stanza-excerpt fallback prompt (which also begins
 *      "landscape, ") can never be mistaken for it: the rest of the text is unique to this spec.
 *   2. The page node v3 created for the scene carries the locked text verbatim as promptText.
 *   3. The node's renderPlan artifact (the plan JSON that was hashed and executed) carries the locked text
 *      verbatim as location.description and its compiled BASE prompt begins with it.
 *   4. The landscape artifact's persisted generatorRequest — the request actually sent to SD — carries the
 *      compiled BASE prompt as its prompt.
 *   5. The scene row is unchanged apart from the image: sdPrompt still the locked text, promptLocked still
 *      true, imageObjectId now set; and STILL no page.<sceneOid> composition — the render path reads, it
 *      does not create (architecture rule: read paths must not create).
 *   6. The PNG is downloaded, validated and written to test-results/p75-check3/ for visual inspection.
 *
 * Gated behind PB_SD_TESTS=1 so the default suite never fires the GPU; run single-threaded:
 *   PB_SD_TESTS=1 PLAYWRIGHT_BASE_URL=https://127.0.0.1:9443 \
 *     npx playwright test e2e/chapBookV3PreV3Lock.spec.js --workers=1 --project=chromium --retries=0
 *
 * Timings are logged, never asserted; the only bounds are the generous test/request timeouts.
 * Runs as ensureSharedTestUser()'s user, never admin. Leaves the book in place (review by hand).
 */
import { test, expect } from '@playwright/test';
import { gunzipSync } from 'zlib';
import { mkdirSync, writeFileSync } from 'fs';
import {
    ensureSharedTestUser, restLoginShared,
    ensurePoemsGroup, ensurePoem, createChapBook, bookPages, sceneByObjectId,
    REST, CB_REST, PB_REST, POEM_2
} from './helpers/chapbook.js';

const SD_ENABLED = process.env.PB_SD_TESTS === '1';
const BASE_URL = process.env.PLAYWRIGHT_BASE_URL || 'https://localhost:8899';
const TAG = '[check3]';
const OUT_DIR = 'test-results/p75-check3';
const TEST_TIMEOUT_MS = 60 * 60 * 1000;
const REQUEST_TIMEOUT_MS = 60 * 60 * 1000;

// Begins with the same "landscape, " the no-LLM stanza-excerpt fallback uses, so a pass cannot be the
// fallback masquerading as the lock; the remainder is unique to this spec.
const LOCKED = 'landscape, a lone basalt lighthouse on a black-sand shore under a green aurora, '
    + 'long exposure, cold teal sea, no people, no text, oil painting';

const upper = s => (s == null ? '' : String(s).toUpperCase());

async function okJson(r, what) {
    const text = await r.text();
    expect(r.ok(), what + ' failed: HTTP ' + r.status() + ' ' + text.slice(0, 600)).toBe(true);
    return JSON.parse(text);
}

async function searchAll(request, type, fields, requestFields) {
    const b = await okJson(await request.post(REST + '/model/search', {
        data: { schema: 'io.query', type, fields, request: requestFields, recordCount: 50, cache: false }
    }), 'search ' + type);
    const rows = Array.isArray(b) ? b : (b && b.results) ? b.results : [];
    return rows;
}

// A pre-V3 writer persisted the lock on the scene row only. The generic PATCH route is that writer's exact
// footprint: schema + identity + the validated name + the two changed fields; nothing else is touched.
async function lockSceneRowOnly(request, scene) {
    const r = await request.patch(REST + '/model', {
        data: { schema: 'olio.pb.scene', objectId: scene.objectId, name: scene.name, sdPrompt: LOCKED, promptLocked: true }
    });
    expect(r.ok(), 'scene-only lock PATCH failed: ' + r.status() + ' ' + await r.text()).toBe(true);
}

async function pageCompositions(request, sceneOid, orgId) {
    return searchAll(request, 'olio.pb.composition', [
        { name: 'name', comparator: 'EQUALS', value: 'page.' + sceneOid },
        { name: 'organizationId', comparator: 'EQUALS', value: Number(orgId) }
    ], ['id', 'objectId', 'name', 'purpose', 'promptOverride', 'promptLocked']);
}

async function sceneRow(request, sceneOid) {
    const rows = await searchAll(request, 'olio.pb.scene',
        [{ name: 'objectId', comparator: 'EQUALS', value: sceneOid }],
        ['id', 'objectId', 'groupId', 'name', 'sceneIndex', 'sdPrompt', 'promptLocked', 'imageObjectId', 'imageStale']);
    expect(rows.length, 'scene ' + sceneOid + ' readable').toBe(1);
    return rows[0];
}

async function awaitJob(request, jobId) {
    for (;;) {
        const j = await okJson(await request.get(REST + '/job/' + jobId), 'GET /job/' + jobId);
        if (j.terminal) return j;
        await new Promise(resolve => setTimeout(resolve, 3000));
    }
}

function chainOf(view, role) {
    const arts = (view && view.artifacts) || {};
    const key = Object.keys(arts).find(k => k.toLowerCase() === role.toLowerCase());
    return key ? arts[key] : [];
}

// Every string-valued key named "prompt" at any depth of the (sanitized, nested) backend request.
function promptStrings(node, out = []) {
    if (Array.isArray(node)) { node.forEach(v => promptStrings(v, out)); }
    else if (node && typeof node === 'object') {
        for (const [k, v] of Object.entries(node)) {
            if (k.toLowerCase() === 'prompt' && typeof v === 'string') out.push(v);
            else promptStrings(v, out);
        }
    }
    return out;
}

async function savePng(request, PB, artifactObjectId, fileName) {
    const art = await okJson(await request.get(PB + '/artifact/' + artifactObjectId), 'GET artifact ' + artifactObjectId);
    expect(art.dataObjectId, 'artifact.dataObjectId').toBeTruthy();
    const dataRec = await okJson(await request.get(REST + '/model/data.data/' + art.dataObjectId), 'GET data.data');
    expect(dataRec && dataRec.groupPath && dataRec.name, 'data.data carries groupPath + name').toBeTruthy();
    const mediaUrl = BASE_URL + '/AccountManagerService7/media/Development/data.data' + dataRec.groupPath + '/' + encodeURIComponent(dataRec.name);
    const media = await request.get(mediaUrl);
    expect(media.ok(), 'GET media ' + mediaUrl + ' HTTP ' + media.status()).toBe(true);
    let raw = await media.body();
    if (raw[0] === 0x1f && raw[1] === 0x8b) raw = gunzipSync(raw);
    expect(raw.subarray(0, 8).toString('hex'), fileName + ' bytes are a PNG').toBe('89504e470d0a1a0a');
    const dims = [raw.readUInt32BE(16), raw.readUInt32BE(20)];
    expect(dims[0] > 0 && dims[1] > 0, 'PNG has dimensions').toBe(true);
    mkdirSync(OUT_DIR, { recursive: true });
    const pngPath = OUT_DIR + '/' + fileName;
    writeFileSync(pngPath, raw);
    await test.info().attach(fileName, { path: pngPath, contentType: 'image/png' });
    console.log(TAG + '-png ' + fileName + ' ' + dims[0] + 'x' + dims[1] + ' (' + raw.length + ' bytes) role=' + art.role
        + ' revision=' + art.revision + ' selected=' + art.selected + ' backend=' + art.backend + ' seed=' + art.seed
        + ' durationMs=' + art.durationMs + ' reviewStatus=' + art.reviewStatus + ' -> ' + pngPath);
    return { art, dims, pngPath };
}

test.describe('V3 check 3 — pre-V3 ChapBook renders a page in V3 with its locked prompt intact', () => {

    test('scene-only lock (no composition) is rendered verbatim on v3', async ({ request }) => {
        test.skip(!SD_ENABLED, 'set PB_SD_TESTS=1 to run the live SD check');
        test.setTimeout(TEST_TIMEOUT_MS);

        // ── 0. A fresh ChapBook in the pre-V3 shape ──
        await ensureSharedTestUser(request);
        await restLoginShared(request);
        const { groupId, organizationId } = await ensurePoemsGroup(request);
        const poemOid = await ensurePoem(request, groupId, organizationId, 'E2E-CB-Poem-2', 'Winter', POEM_2);
        const slug = 'e2e-cb-prev3-lock-' + Date.now();
        const bookOid = await createChapBook(request, slug, 'E2E pre-V3 locked ChapBook', [poemOid], 40);
        const PB = PB_REST + '/' + bookOid;
        const pages = await bookPages(request, bookOid);
        expect(pages.length, 'book has at least one page').toBeGreaterThanOrEqual(1);
        const sceneOid = pages[0].objectId;
        console.log(TAG + ' book ' + slug + ' ' + bookOid + ' pages=' + pages.length + ' scene0=' + sceneOid
            + ' page0=' + JSON.stringify({ imageName: pages[0].imageName, sceneNodeObjectId: pages[0].sceneNodeObjectId, nodeStatus: pages[0].nodeStatus }));
        expect(pages[0].sceneNodeObjectId == null, 'create links no scene.sceneNode (pre-V3 shape)').toBe(true);
        expect(pages[0].imageName, 'a fresh page has no image').toBeFalsy();

        const before = await sceneRow(request, sceneOid);
        console.log(TAG + ' scene before: ' + JSON.stringify({ sdPrompt: before.sdPrompt, promptLocked: before.promptLocked, imageObjectId: before.imageObjectId }));
        expect(before.promptLocked, 'a fresh page is not locked').toBeFalsy();
        expect(before.imageObjectId, 'a fresh page has no image').toBeFalsy();

        await lockSceneRowOnly(request, before);
        const locked = await sceneByObjectId(request, sceneOid);
        expect(locked.sdPrompt, 'the lock is on the scene row').toBe(LOCKED);
        expect(locked.promptLocked, 'promptLocked on the scene row').toBe(true);
        const compsBefore = await pageCompositions(request, sceneOid, organizationId);
        expect(compsBefore, 'the pre-V3 shape has no page composition: ' + JSON.stringify(compsBefore)).toEqual([]);

        // ── 1. Render the page on v3 with no override: the lock must be what is rendered ──
        const started = Date.now();
        const r = await request.post(CB_REST + '/scene/' + sceneOid + '/generate', {
            data: { schema: 'olio.pictureBookRequest' }, timeout: REQUEST_TIMEOUT_MS
        });
        const text = await r.text();
        const ms = Date.now() - started;
        console.log(TAG + ' generate HTTP ' + r.status() + ' in ' + ms + 'ms -> ' + text.slice(0, 900));
        expect([200, 202].includes(r.status()), 'generate answered HTTP ' + r.status() + ' ' + text.slice(0, 500)).toBe(true);
        const body = JSON.parse(text);
        expect(body.renderPath, 'the page went down the v3 path').toBe('v3');
        expect(body.skipped, 'not skipped').toBe(false);
        expect(body.llmUnavailable, 'a locked prompt never reports the LLM unavailable').toBe(false);
        expect(body.llmDegraded, 'a locked prompt is never a degraded prompt').toBe(false);
        expect(body.jobId && body.runObjectId && body.nodeObjectId, 'v3 job ids: ' + text.slice(0, 300)).toBeTruthy();
        let artifactObjectId = body.artifactObjectId;
        let nodeStatus = body.nodeStatus;
        if (r.status() === 202) {
            expect(body.pending, 'a 202 is the PENDING shape').toBe(true);
            const job = await awaitJob(request, body.jobId);
            console.log(TAG + ' polled job -> ' + JSON.stringify(job).slice(0, 900));
            expect(job.status).toBe('completed');
            const n = (job.result && job.result.nodes || []).find(x => x.nodeObjectId === body.nodeObjectId);
            expect(n, 'the job names the page node').toBeTruthy();
            artifactObjectId = n.artifactObjectId;
            nodeStatus = n.status;
        } else {
            expect(body.rendered, 'rendered (job COMPLETED, node DONE, image present)').toBe(true);
        }
        expect(artifactObjectId, 'a landscape artifact').toBeTruthy();
        expect(['DONE', 'DONE_UNVERIFIED'], 'node status ' + nodeStatus).toContain(upper(nodeStatus));

        // ── 2. The page node carries the locked text verbatim ──
        const nv = await okJson(await request.get(PB + '/workflow/node/' + body.nodeObjectId), 'GET workflow/node');
        console.log(TAG + ' node ' + nv.handle + ' storedStatus=' + nv.storedStatus + ' promptText=' + JSON.stringify(nv.promptText)
            + ' roles=' + JSON.stringify(Object.keys(nv.artifacts || {})));
        expect(nv.promptText, 'node.promptText is the locked prompt verbatim').toBe(LOCKED);

        // ── 3. The plan that was executed: location.description verbatim; compiled BASE begins with it ──
        const planChain = chainOf(nv, 'renderPlan');
        expect(planChain.length, 'the node has a renderPlan artifact').toBeGreaterThanOrEqual(1);
        const planArt = await okJson(await request.get(PB + '/artifact/' + planChain[planChain.length - 1].objectId), 'GET plan artifact');
        expect(upper(planArt.role)).toBe('RENDERPLAN');
        const plan = JSON.parse(planArt.artifactText);
        console.log(TAG + ' plan location=' + JSON.stringify(plan.location) + ' strategy=' + JSON.stringify(plan.strategy)
            + ' models=' + JSON.stringify(plan.models) + ' degradations=' + JSON.stringify(plan.degradations || [])
            + ' compiledStages=' + JSON.stringify(Object.keys(plan.compiled || {})));
        expect(plan.location && plan.location.description, 'plan.location.description is the locked prompt verbatim').toBe(LOCKED);
        const base = plan.compiled && plan.compiled.BASE;
        expect(base && base.prompt, 'a compiled BASE prompt').toBeTruthy();
        console.log(TAG + ' compiled BASE prompt: ' + JSON.stringify(base.prompt));
        expect(base.prompt.startsWith(LOCKED), 'compiled BASE prompt begins with the locked text: ' + base.prompt).toBe(true);

        // ── 4. The request actually sent to SD carries the compiled BASE prompt ──
        const landChain = chainOf(nv, 'landscape');
        expect(landChain.length, 'the node has a landscape artifact').toBeGreaterThanOrEqual(1);
        const sel = landChain.find(a => a.selected) || landChain[landChain.length - 1];
        expect(sel.objectId, 'the selected landscape artifact is the one the body named').toBe(artifactObjectId);
        const landArt = await okJson(await request.get(PB + '/artifact/' + artifactObjectId), 'GET landscape artifact');
        expect(landArt.generatorRequest, 'the landscape artifact persisted its generator request').toBeTruthy();
        const gen = JSON.parse(landArt.generatorRequest);
        const prompts = promptStrings(gen);
        console.log(TAG + ' generatorRequest keys=' + JSON.stringify(Object.keys(gen)) + ' prompts=' + JSON.stringify(prompts));
        expect(prompts.length, 'the generator request carries a prompt').toBeGreaterThanOrEqual(1);
        expect(prompts, 'the SD request prompt is the compiled BASE prompt').toContain(base.prompt);
        expect(prompts.every(p => p.startsWith(LOCKED)), 'every prompt sent to SD begins with the locked text').toBe(true);

        // ── 5. The scene row: lock intact, image set, still no composition ──
        const after = await sceneRow(request, sceneOid);
        console.log(TAG + ' scene after: ' + JSON.stringify({ sdPrompt: after.sdPrompt, promptLocked: after.promptLocked, imageObjectId: after.imageObjectId, imageStale: after.imageStale }));
        expect(after.sdPrompt, 'scene.sdPrompt untouched by the render').toBe(LOCKED);
        expect(after.promptLocked, 'scene.promptLocked untouched by the render').toBe(true);
        expect(after.imageObjectId, 'scene.imageObjectId set by the render').toBe(landArt.dataObjectId);
        expect(after.imageStale, 'scene.imageStale cleared').toBeFalsy();
        const pagesAfter = await bookPages(request, bookOid);
        const page0 = pagesAfter.find(p => p.objectId === sceneOid);
        console.log(TAG + ' page0 after: ' + JSON.stringify({ imageName: page0 && page0.imageName, sceneNodeObjectId: page0 && page0.sceneNodeObjectId, nodeStatus: page0 && page0.nodeStatus }));
        expect(page0 && page0.sceneNodeObjectId, '/pages resolves scene.sceneNode to the page node').toBe(body.nodeObjectId);
        const compsAfter = await pageCompositions(request, sceneOid, organizationId);
        expect(compsAfter, 'the render path created no page composition: ' + JSON.stringify(compsAfter)).toEqual([]);

        // ── 6. The image, for visual inspection ──
        const png = await savePng(request, PB, artifactObjectId, 'check3-prev3-locked-page.png');
        expect(upper(png.art.role)).toBe('LANDSCAPE');
        console.log(TAG + ' RESULT book=' + bookOid + ' scene=' + sceneOid + ' node=' + body.nodeObjectId + ' artifact=' + artifactObjectId
            + ' job=' + body.jobId + ' generateMs=' + ms);
    });
});
